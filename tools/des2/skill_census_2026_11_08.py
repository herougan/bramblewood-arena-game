#!/usr/bin/env python3
# Skill census for DES2 (2026-11-08, package DES2; owner 11-08 10:52: "Seems like there is quite a lot of skills to work around with.
# I agree - let's limit and focus in."). Design analysis only: reads canonical data, changes nothing in the game.
#
# For every skill key on a card (base effects or levelSkills, one per ENG35 family): how many cards carry it in all, and which of
# them sit on a Maps 0-20 main list (canonical/map-pools.json; road order and map numbers from DES1's map-signatures JSON).
# Output: tools/des2/skill_census_2026_11_08.json (read by tools/des2/skill_plan_2026_11_08.py).
# Usage: python3 tools/des2/skill_census_2026_11_08.py
import json, os, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import skill_params  # noqa: E402

OUT = os.path.join(ROOT, 'tools', 'des2', 'skill_census_2026_11_08.json')
PLUMBING = {'arrowCount', 'archerStyle', 'deliveryRes', 'deliveryEvery', 'speeches', 'hatchling', 'stem', 'chrysalis',
            'tribeDeliveryRes', 'resist', 'weakness', 'immune', 'triggers'}


def load(p):
    return json.load(open(os.path.join(ROOT, p), encoding='utf-8'))


def card_skills(card):
    out = set()
    for e in [card.get('effects')] + list((card.get('levelSkills') or {}).values()):
        if not isinstance(e, dict):
            continue
        for k, v in skill_params.fuse(e).items():
            if k in PLUMBING or v in (False, None, 0, '', []):
                continue
            out.add(k)
    return out


def main():
    cards = load('canonical/cards.json')
    by_id = {c['id']: c for c in cards}
    pools = load('canonical/map-pools.json')['maps']
    des1 = load('docs/design/map-signatures-2026-11-08.json')
    mains = [m for m in des1['maps'] if m['kind'] == 'main' and m['id'] != 'mtut']
    first_map = {}
    for m in mains:
        for cid in pools.get(m['id'], {}).get('cards', []):
            first_map.setdefault(cid, m['no'])
    allc, road = collections.defaultdict(list), collections.defaultdict(list)
    for c in cards:
        for k in card_skills(c):
            allc[k].append(c['name'])
            if c['id'] in first_map:
                road[k].append('%s (M%s)' % (c['name'], first_map[c['id']]))
    out = {'_about': 'DES2 skill census (2026-11-08): per skill key, how many cards carry it (all) and the ones on a Maps 0-20 main '
                     'list (with the first main map that lists them). Generated by tools/des2/skill_census_2026_11_08.py.',
           'roadCards': {by_id[cid]['name']: no for cid, no in first_map.items() if cid in by_id},
           'skills': {k: {'all': len(allc[k]), 'road': sorted(road.get(k, []))} for k in sorted(allc)}}
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
    print('skills', len(allc), 'road cards', len(first_map))


if __name__ == '__main__':
    main()
