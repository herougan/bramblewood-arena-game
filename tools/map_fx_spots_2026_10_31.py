#!/usr/bin/env python3
"""2026-10-31 (package MAPFX1): list where the painted maps' crystals, water, bushes and trees are.

The map backgrounds are painted by tools/make_map_backgrounds.py (deterministic per map). This re-runs each painter with its
scatter/ponds/river calls logged, checks the result is pixel-identical to the shipped assets/maps/<id>.png (so the positions are
true for the art the player sees), and prints a JS table (% of the 256x144 art; t = trees, b = bushes and reeds, c = crystals, w = water [x, y, w, h]) for arena_app.js's MAP_FX_SPOTS.
A map whose shipped art differs from the painter (AI-painted or swapped) is left out, so it simply has no spots.

    python3 tools/map_fx_spots_2026_10_31.py > spots.js
"""
import os, sys, json, tempfile, importlib.util
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
spec = importlib.util.spec_from_file_location('mmb', os.path.join(HERE, 'make_map_backgrounds.py')); M = importlib.util.module_from_spec(spec); spec.loader.exec_module(M)
W, H = M.W, M.H
LOG = []
KIND = {id(M.PINE): 'tree', id(M.ROUND): 'tree', id(M.SNOWPINE): 'tree', id(M.ACACIA): 'tree', id(M.DEAD): 'tree',
        id(M.BUSH): 'bush', id(M.REED): 'bush', id(M.CRYSTAL): 'crystal'}
_scatter, _ponds, _river, _stamp = M.scatter, M.ponds, M.river, M.stamp


def scatter(img, rng, sprite, pal, n, **kw):
    k = KIND.get(id(sprite)); sw, sh = max(len(r) for r in sprite), len(sprite)

    def st(img2, spr, x, y, p):
        if spr is sprite and k:
            LOG.append((k, x + sw / 2, y + sh / 2, sw, sh))
        return _stamp(img2, spr, x, y, p)
    M.stamp = st
    try:
        return _scatter(img, rng, sprite, pal, n, **kw)
    finally:
        M.stamp = _stamp


def ponds(img, rng, n, *a, **kw):
    m = _ponds(img, rng, n, *a, **kw)
    from scipy import ndimage
    lab, cnt = ndimage.label(m)
    for i in range(1, cnt + 1):
        yy, xx = np.nonzero(lab == i)
        if len(xx) > 30:
            LOG.append(('water', float(xx.mean()), float(yy.mean()), float(xx.max() - xx.min() + 1), float(yy.max() - yy.min() + 1)))
    return m


def river(img, rng, *a, **kw):
    m = _river(img, rng, *a, **kw)
    for q in range(8, W - 8, 34):
        col = np.nonzero(m[:, q])[0]
        if len(col):
            LOG.append(('water', float(q), float(col.mean()), 22.0, 8.0))
    return m


M.scatter, M.ponds, M.river = scatter, ponds, river
out = {}; skipped = []
tmp = tempfile.mkdtemp(prefix='mapfx1_')
M.OUT = tmp
for mid in sorted(M.PAINTERS):
    LOG.clear()
    try:
        p = M.make(mid)
    except Exception as e:
        skipped.append((mid, 'error ' + str(e)[:40])); continue
    shipped = os.path.join(ROOT, 'assets', 'maps', mid + '.png')
    if not os.path.exists(shipped):
        skipped.append((mid, 'no art')); continue
    a, b = np.array(Image.open(p).convert('RGB')), np.array(Image.open(shipped).convert('RGB'))
    if a.shape != b.shape or (a != b).sum() > 0:
        skipped.append((mid, 'differs')); continue
    d = {}
    for k, x, y, w, h in LOG:
        if not (2 <= x / W * 100 <= 98 and 3 <= y / H * 100 <= 97):
            continue  # on the edge: no room for a tap target
        if k == 'water':
            if w >= 6:
                d.setdefault('w', []).append([round(x / W * 100, 1), round(y / H * 100, 1), round(w / W * 100, 1), round(h / H * 100, 1)])
        else:
            d.setdefault(k[0], []).append([round(x / W * 100, 1), round(y / H * 100, 1)])
    out[mid] = d
print('// generated by tools/map_fx_spots_2026_10_31.py; skipped (art not from the painter): ' + ', '.join(f'{a}:{b}' for a, b in skipped))
print('const MAP_FX_SPOTS = ' + json.dumps(out, separators=(',', ':')) + ';')
