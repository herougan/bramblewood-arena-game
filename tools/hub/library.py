# still relevant."): the 📖 Library tab. Every docs/**/*.md is classified here and shown in the hub, so the owner reads them in one place; the files stay
# on disk (agents and tools read them).
#   canonical  = CLAUDE.md's source-of-truth table (code map, style guideline, art prompts, lore bible, effects catalogue, tuning guide, workflows ...)
#   reference  = design docs and guides that are not dated
#   history    = dated snapshots (*-2026-10-*), retired and generated status docs; a collapsed group, titles + one line, each rendered on demand
# A doc the hub already renders in another tab (Action items, Changelog, Decisions, Progression plan, Design, Claude's guide) is linked to that tab,
# never repeated. docs/balance and docs/art are raw outputs and prompt files that tools read, so they stay out.
# Plain module (no hub build state) so tests/hub4-2026-10-24.js can run it against a stub page: build(root, md_html, anchor, txt, elsewhere, search).
import os, re, json, html as H, subprocess

SKIP_DIRS = ('balance', 'art')
CANONICAL = {  # file -> what it is the source of truth for (CLAUDE.md table)
    'code-map.md': 'Where code lives (generated by tools/code_map.py)',
    'style-guideline.md': 'Art direction',
    'art-style-prompts.md': 'Art prompts',
    'lore-bible.md': 'Lore and names',
    'effects-catalogue.md': 'Describes the keywords; the engine decides',
    'skirmish-tuning-guide.md': 'How to tune a skirmish',
    'project-state.md': 'The settled rules, each with its decision id',  # 2026-10-25 (package DOCS1, D1)
    'evaluation-protocol.md': 'PRO rules, reference decks, difficulty tolerance, testing procedure',  # 2026-10-25 (package DOCS1, D2)
    'workflows/art.md': 'Workflow: art generation and visual review', 'workflows/balance.md': 'Workflow: balance analysis and simulations',
    'workflows/card-data.md': 'Workflow: card data and content', 'workflows/engine.md': 'Workflow: engine and backend',
    'workflows/release.md': 'Workflow: testing, debugging, releases', 'workflows/ui.md': 'Workflow: UI and frontend',
}
TAB_DOCS = {  # canonical docs with their own hub tab
    'action-items.md': ('actions', '🎯 Action items'), 'CHANGELOG.md': ('changelog', '🗒️ Changelog'),
    'decisions.md': ('decisions', '🗳️ Decisions'), 'progression-plan.md': ('progress', '📚 Progression plan'),
}
HISTORY_NAMES = {  # not dated in the name, but snapshots or retired
    'MASTER.md': 'Retired 2026-10-09 (the hub replaced it)',
    'game-design-v39-addendum.md': 'Addendum to an old design version', 'game-design-v40-addendum.md': 'Addendum to an old design version',
}
DATED = re.compile(r'(?:^|[-_/])20\d\d-\d\d-\d\d')
STATUS = re.compile(r'^fx-batch-[a-z]-status\.md$')

def slug(rel): return 'lib-' + re.sub(r'[^a-z0-9]+', '-', rel[:-3].lower()).strip('-')

def classify(rel):
    if rel in TAB_DOCS or rel in CANONICAL: return 'canonical'
    if rel.startswith('archive/') or rel in HISTORY_NAMES or DATED.search(rel) or STATUS.match(rel): return 'history'
    return 'reference'

def list_docs(root):
    out = []
    base = os.path.join(root, 'docs')
    for dp, dn, fs in os.walk(base):
        rel_dir = os.path.relpath(dp, base)
        if rel_dir == '.': dn[:] = [d for d in dn if d not in SKIP_DIRS]
        for f in sorted(fs):
            if f.endswith('.md'): out.append(os.path.normpath(os.path.join(rel_dir, f)).replace(os.sep, '/'))
    return sorted(out)

def git_dates(root):  # file -> last commit date (YYYY-MM-DD); one git call
    d = {}
    try:
        r = subprocess.run(['git', 'log', '--name-only', '--format=%x01%cs', '--', 'docs'], cwd=root, capture_output=True, text=True, timeout=120)
        cur = ''
        for ln in r.stdout.split('\n'):
            if ln.startswith('\x01'): cur = ln[1:].strip()
            elif ln.strip().startswith('docs/') and ln.strip()[5:] not in d: d[ln.strip()[5:]] = cur
    except Exception: pass
    return d

def title_summary(md, rel):
    title = ''; summ = ''
    for ln in md.split('\n'):
        s = ln.strip()
        if not title and s.startswith('# '): title = re.sub(r'[*_`]', '', s[2:]).strip(); continue
        if title and not summ and s and not s.startswith(('#', '|', '---', '<!--', '```', '- ', '* ')) and not re.match(r'^\d+\.', s):
            t = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', s); t = re.sub(r'^[>\s_*]+|[*_`]+', '', t).strip()
            if len(t) > 20: summ = t
        if title and summ: break
    if not title: title = os.path.basename(rel)[:-3].replace('-', ' ')
    if len(summ) > 190: summ = summ[:187].rsplit(' ', 1)[0] + '…'
    return title, summ

def build(root, md_html, anchor, txt, elsewhere, search, dates=None):
    """elsewhere: rel path -> (tab, label, sub|None) for docs rendered in another tab. Appends to `search`. Returns (panel_html, counts)."""
    dates = git_dates(root) if dates is None else dates
    rows = {'canonical': [], 'reference': [], 'history': []}; panes = ''
    counts = {'canonical': 0, 'reference': 0, 'history': 0, 'linked': 0, 'rendered_here': 0}
    for rel in list_docs(root):
        md = open(os.path.join(root, 'docs', rel), encoding='utf-8').read()
        kind = classify(rel); title, summ = title_summary(md, rel); counts[kind] += 1
        when = dates.get(rel, '')
        link = elsewhere.get(rel) or ((TAB_DOCS[rel] + (None,)) if rel in TAB_DOCS else None)
        note = CANONICAL.get(rel, HISTORY_NAMES.get(rel, ''))
        hay = H.escape((title + ' ' + rel + ' ' + summ + ' ' + note).lower(), quote=True)
        meta = f'<code>docs/{H.escape(rel)}</code> · last changed {H.escape(when) or "?"}'
        stype = 'History' if kind == 'history' else 'Library'
        if link:
            counts['linked'] += 1
            go = H.escape(json.dumps({'tab': link[0], **({'sub': link[2]} if link[2] else {})}), quote=True)
            act = f'<a href="#{link[0]}" data-go="{go}">shown in {H.escape(link[1])} →</a>'
        else:
            sid = slug(rel); counts['rendered_here'] += 1
            act = f'<a class="jump" href="#{sid}">Read</a>'
            h, secs = anchor(md_html(md), sid)
            for s_id, s_t, s_x in secs:
                search.append([stype, s_t, title + (' (history)' if kind == 'history' else ''), s_x[:1200 if kind == 'history' else 3000], {'tab': 'doclib', 'sub': sid, 'el': s_id}])
            if not secs: search.append([stype, title, rel, txt(h)[:1200], {'tab': 'doclib', 'sub': sid}])
            body = f'<div class="doc">{h}</div>'
            if kind == 'history': body = '<template class="lazy">' + body + '</template>'  # rendered on demand: stamped out when opened
            panes += (f'<div class="subpane lib-pane" data-group="lib" id="{sid}" hidden><p class="lib-back"><a class="jump" href="#lib-index">← Library</a> · {meta}'
                      f'{" · <b>history</b>: a dated snapshot; the canonical source wins where they differ" if kind == "history" else ""}</p>'
                      f'{body}</div>')
        line = (note + '. ' if note and kind != 'history' else '') + summ
        rows[kind].append((title.lower(), f'<li class="lib-row" data-hay="{hay}"><span class="lib-t"><b>{H.escape(title)}</b> {act}</span>'
                           f'<span class="lib-m">{meta}</span>' + (f'<span class="lib-s">{H.escape(line)}</span>' if line else '') + '</li>'))
    def group(k): return ''.join(r for _, r in sorted(rows[k]))
    index = ('<div class="subpane lib-pane" data-group="lib" id="lib-index"><h1>📖 Library</h1>'
        '<p class="lede">Every document in <code>docs/</code>, read here. The files stay on disk (Claude and the tools read them); this tab is the one place to read them. '
        'The search box at the top (<kbd>/</kbd>) searches all of them; the box below filters this list.</p>'
        '<p><input type="search" id="libQ" placeholder="Filter by title, path or topic…" aria-label="Filter the library"> <span class="note" id="libN" aria-live="polite"></span></p>'
        f'<h2>Canonical <small>{counts["canonical"]}</small></h2><p class="note">The source of truth for one kind of information (CLAUDE.md’s table). Docs with their own tab link to it.</p><ul class="lib-list">{group("canonical")}</ul>'
        f'<h2>Reference <small>{counts["reference"]}</small></h2><p class="note">Design docs and guides that are still in use and not tied to a date.</p><ul class="lib-list">{group("reference")}</ul>'
        f'<details class="lib-hist"><summary>🕰️ History <small>{counts["history"]} dated snapshots</small></summary><p class="note">Balance passes, proposals, audits and status sheets from one moment. Where one disagrees with a canonical source, the canonical source wins. Each opens on demand.</p><ul class="lib-list">{group("history")}</ul></details>'
        '<p class="note">Left out on purpose: <code>docs/balance</code> (raw simulation output) and <code>docs/art</code> (prompt files that tools read).</p></div>')
    return '<div class="doc lib">' + index + panes + '</div>', counts
