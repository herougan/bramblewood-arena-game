#!/usr/bin/env python3
# Code map generator (2026-10-21, workflow audit). Writes docs/code-map.md: where each game system lives in the big files,
# so a task can open the right lines instead of searching 50k lines. Derived from the source: never edit the .md by hand,
# rerun `python3 tools/code_map.py` after large changes (it takes about a second). Line numbers drift between runs;
# the names are what to grep for.
import re, os, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

AREAS = [  # (area, keywords matched against camelCase / UPPER_SNAKE name parts, lowercased)
    ('Raid', 'raid tentacle shard maw boss elder'),
    ('Multiplayer, arenas and guilds', 'pvp live match arena async ghost tavern guild peer relay ladder tower ambush'),
    ('Forge, Nest and crafting', 'forge temper melt fuse reinforce refine nest hatch materia dust limitbreak craft disenchant enchant prestige blacksmith egg'),
    ('Deck editor and filters', 'deck editor filter sort swap suggest loadout'),
    ('Codex, collection and album', 'codex collection album book library unseen'),
    ('Map, road, skirmish and quests', 'map road node skirmish wildpath submap quest dungeon world gate trench cave tide errand stamina'),
    ('Rewards, packs, shop and factions', 'reward pack shop gold bounty faction economy price chest key keys leaves market grant drop xp'),
    ('Tutorial, dialogue and hero', 'tutorial dialogue story hero npc talk intro lore lesson'),
    ('Battle UI and board', 'battle board lane hand slot turn play attack combat field enemy ally vs fight round meter hp damage status chip castle energy sweep'),
    ('Admin, profile, cloud and sync', 'admin profile cloud sync supabase save login account settings reset backup override'),
    ('Cards, levels and skills', 'card cards def defs level skill stat stats cost rarity leader copy tier rank class pool'),
    ('Text and translation', 'tx lang i18n text translate locale'),
    ('Effects, art and audio', 'fx sfx anim shine emoji audio sound art frame particle shader glow vfx fxl tip hover'),
    ('Tests and dev tools', 'testkit debug dev cheat qa'),
]
AREA_KEYS = [(a, set(k.split())) for a, k in AREAS]

def parts(name):
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1 \2', name).replace('_', ' ').replace('$', ' ')
    return [p.lower() for p in s.split() if p]

def area_of(name):
    ps = parts(name)
    joined = ''.join(ps)
    for a, keys in AREA_KEYS:
        if any(p in keys for p in ps) or any(k in joined for k in keys if len(k) >= 5):
            return a
    return None

def scan(path):
    fn_re = re.compile(r'^\s{0,4}(?:async\s+)?function\s+([A-Za-z_$][\w$]*)')
    const_re = re.compile(r'^(?:const|let|var)\s+([A-Z][A-Z0-9_]{3,})\s*=')
    fns, consts = [], []
    with open(path, encoding='utf-8') as f:
        for i, line in enumerate(f, 1):
            m = fn_re.match(line)
            if m: fns.append((m.group(1), i)); continue
            m = const_re.match(line)
            if m: consts.append((m.group(1), i))
    return fns, consts

def spans(lines, gap=1500):
    lines = sorted(lines)
    out, start, prev = [], None, None
    for l in lines:
        if start is None: start = prev = l; continue
        if l - prev > gap: out.append((start, prev)); start = l
        prev = l
    if start is not None: out.append((start, prev))
    # keep the spans that hold most of the area
    return sorted(out, key=lambda s: -(s[1] - s[0]))[:4]

def count_lines(p):
    with open(p, encoding='utf-8', errors='ignore') as f: return sum(1 for _ in f)

out = ['# Code map (generated)', '',
       '> Generated by `python3 tools/code_map.py` from the source. Do not edit by hand; rerun after big changes.',
       '> Line numbers drift: grep for the **names**. Area guesses come from the names, so a few entries sit in the wrong area.', '']

# Other files: role table (stable, hand-written here because it changes rarely)
ROLES = [
    ('arena_app.js', 'All game UI and meta-game: screens, Forge, Codex, deck editor, map, raid UI, saves. Mapped below.'),
    ('arena_template.html', 'Page shell and almost all CSS. assemble_arena.py inlines the scripts into it.'),
    ('bramblewood-engine.js', 'DOM-free battle rules: combat order, keywords, skills, statuses, AI. Tests run it headless.'),
    ('bramblewood-budget.js', 'Card budget N(L) and the stat checks (the balance formula).'),
    ('bramblewood-texts.js', 'Every player-facing string as a TX key (English). Translations: lang/<code>.json keyed by the English text.'),
    ('bramblewood-raid.js / -trench.js / -ghosts.js / -autobattle.js', 'Raid rules, the trench, Async Arena ghosts, autobattler.'),
    ('bramblewood-fx-a..g.js, -skillfx.js, -unitfx.js, -procfx.js, -shaders.js', 'Visual effects.'),
    ('canonical/*.json', 'Card data (cards.json is the source of truth), raids, monsters, skill costs, animal tags.'),
    ('assemble_arena.py', 'Build: writes bramblewood-arena.html (rename to index.html) and assets/lang/*.js.'),
    ('tests/run-all.sh', 'The list of tests. Run them with tests/run.js (tiers, cache, quiet output).'),
    ('tools/hub/', 'The project hub artifact (build_hub.py, publish_site.sh) and the db-edit fold scripts.'),
]
out += ['## Files', '', '| File | What it holds | Lines |', '|---|---|---|']
for f, role in ROLES:
    first = f.split(' ')[0]
    n = count_lines(first) if os.path.isfile(first) else ''
    out.append(f'| `{f}` | {role} | {n} |')
out.append('')

for path in ['arena_app.js', 'bramblewood-engine.js']:
    fns, consts = scan(path)
    by_area = collections.defaultdict(lambda: {'fns': [], 'consts': []})
    for n, l in fns: by_area[area_of(n) or 'Other']['fns'].append((n, l))
    for n, l in consts: by_area[area_of(n) or 'Other']['consts'].append((n, l))
    out += [f'## {path}', '', f'{len(fns)} top-level functions, {len(consts)} UPPER_CASE constants or package blocks.', '']
    order = [a for a, _ in AREAS] + ['Other']
    for a in order:
        if a not in by_area: continue
        d = by_area[a]
        allines = [l for _, l in d['fns'] + d['consts']]
        sp = ', '.join(f'L{s}–{e}' for s, e in sorted(spans(allines)))
        out.append(f'### {a} ({len(d["fns"])} functions)')
        out.append(f'Main spans: {sp}')
        if d['consts']:
            out.append('Blocks and tables: ' + ', '.join(f'`{n}` L{l}' for n, l in d['consts'][:40]) + (' …' if len(d['consts']) > 40 else ''))
        if a != 'Other':
            out.append('Functions: ' + ', '.join(f'`{n}` L{l}' for n, l in d['fns'][:60]) + (f' … and {len(d["fns"]) - 60} more' if len(d['fns']) > 60 else ''))
        out.append('')

open('docs/code-map.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote docs/code-map.md', sum(len(x) for x in out), 'chars')
